import { chromium } from '@playwright/test';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { spawn } from 'node:child_process';
import path from 'node:path';
const base=process.env.DEMO_URL || 'http://127.0.0.1:3100';
const directory=path.resolve('artifacts');mkdirSync(directory,{recursive:true});
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || 'chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();
const session=await context.newCDPSession(page);
const frames=[];
session.on('Page.screencastFrame',async event=>{frames.push(Buffer.from(event.data,'base64'));await session.send('Page.screencastFrameAck',{sessionId:event.sessionId});});
await session.send('Page.startScreencast',{format:'jpeg',quality:85,maxWidth:1440,maxHeight:1000,everyNthFrame:1});
await page.goto(base);
const pause=()=>new Promise(r=>setTimeout(r,900));
await pause();await page.getByRole('button',{name:'Generate dashboard',exact:true}).click();await page.waitForFunction(()=>!document.querySelector('[aria-busy="true"]'));await pause();
await page.screenshot({path:path.join(directory,'dashboard-desktop.png'),fullPage:true});
await page.getByRole('button',{name:/Accounts at risk/}).click();await page.waitForFunction(()=>!document.querySelector('[aria-busy="true"]'));await pause();
await page.getByRole('button',{name:'Filters',exact:true}).click();await page.getByLabel('Customer status',{exact:true}).selectOption('At risk');await pause();
await page.getByRole('button',{name:'Save view',exact:true}).click();await page.getByLabel('Dashboard name').fill('Accounts to watch');await page.getByRole('button',{name:'Save dashboard',exact:true}).click();await pause();
await page.getByRole('button',{name:'Clear filters'}).click();await page.getByRole('button',{name:/Billing & conversion/}).click();await page.waitForFunction(()=>!document.querySelector('[aria-busy="true"]'));await pause();
await page.screenshot({path:path.join(directory,'billing-demo.png'),fullPage:true});
await session.send('Page.stopScreencast');
await page.setViewportSize({width:375,height:900});await page.goto(base);await page.screenshot({path:path.join(directory,'dashboard-mobile.png'),fullPage:true});
await context.close();await browser.close();
// Encode captured browser frames into a silent, portable walkthrough.
const temp=path.join(directory,'frames');mkdirSync(temp,{recursive:true});
frames.forEach((frame,i)=>writeFileSync(path.join(temp,`${String(i).padStart(5,'0')}.jpg`),frame));
const ffmpeg=spawn('ffmpeg',['-y','-framerate','8','-i',path.join(temp,'%05d.jpg'),'-vf','pad=ceil(iw/2)*2:ceil(ih/2)*2','-c:v','libx264','-pix_fmt','yuv420p','-movflags','+faststart',path.join(directory,'demo-walkthrough.mp4')],{stdio:'ignore'});
await new Promise((resolve,reject)=>{ffmpeg.once('error',reject);ffmpeg.once('exit',code=>code===0?resolve():reject(new Error(`ffmpeg exited ${code}`)));});
rmSync(temp,{recursive:true,force:true});console.log(`Saved ${frames.length} frames and screenshots in ${directory}`);
